import { test, expect } from '@playwright/test'
test('installed package handles local and real mock API interactions', async ({page}) => {
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Customer directory'})).toBeVisible()
 await page.getByRole('checkbox',{name:'Select row 1',exact:true}).check()
 await expect(page.getByText('1 selected',{exact:false})).toBeVisible()
 await page.getByRole('button',{name:'Columns',exact:true}).click()
 await page.getByRole('dialog').getByLabel('Email',{exact:true}).uncheck()
 await page.getByRole('button',{name:'Apply',exact:true}).click()
 await expect(page.getByRole('columnheader',{name:'Email'})).toHaveCount(0)
 await page.reload()
 await expect(page.getByRole('columnheader',{name:'Email'})).toHaveCount(0)
 const download = page.waitForEvent('download')
 await page.getByRole('button',{name:'Export',exact:true}).click()
 await page.getByRole('button',{name:'CSV — Current page',exact:true}).click()
 expect((await download).suggestedFilename()).toBe('export.csv')
 await page.getByRole('button',{name:'Async provider',exact:true}).click()
 await expect(page.locator('tbody tr')).toHaveCount(10)
 await page.getByRole('button',{name:'Filters',exact:true}).click()
 await page.getByLabel('Customer · Value',{exact:true}).fill('Ada')
 await expect(page.locator('tbody tr')).toHaveCount(8)
 await page.getByRole('button',{name:'Slots & actions',exact:true}).click()
 await page.getByRole('button',{name:'Inspect Ada Morgan 1',exact:true}).click()
 await expect(page.getByText('Inspecting Ada Morgan 1',{exact:true})).toBeVisible()
 expect(errors).toEqual([])
})
test('provider states and mobile RTL work in the built consumer', async ({page})=>{
 await page.goto('/#states')
 await expect(page.getByRole('button',{name:'Retry'})).toBeVisible()
 await page.getByRole('button',{name:'Restore server for retry'}).click()
 await page.getByRole('button',{name:'Retry'}).click()
 await expect(page.locator('tbody tr')).toHaveCount(25)
 await page.getByRole('button',{name:'Empty result'}).click()
 await expect(page.getByText('No items to display',{exact:false})).toBeVisible()
 await page.getByRole('button',{name:'Successful result'}).click()
 await expect(page.locator('tbody tr')).toHaveCount(25)
 await page.setViewportSize({width:375,height:900})
 await page.getByRole('button',{name:'فارسی / RTL'}).click()
 await expect(page.locator('.sdt-root')).toHaveAttribute('dir','rtl')
 await expect(page.locator('.sdt-mobile')).toBeVisible()
 await page.getByRole('button',{name:'تم تیره'}).click()
 await expect(page.locator('.sdt-root')).toHaveAttribute('data-sdt-theme','dark')
})
